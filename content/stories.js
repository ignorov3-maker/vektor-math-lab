  const fr = (n, d) => `<span class="frac"><span>${n}</span><span>${d}</span></span>`;
  const KNOWN = ['n', 'k', 'r', 'N', 'M', 'f', 'x', 'y'];
  // значения меток для задачи → { name: число | html-дробь }
  function values(p) {
    if (!p) return null;
    if (p.kind === 'left' || p.kind === 'shaded') return { n: p.n, k: p.k, r: p.n - p.k };
    if (p.kind === 'part') return { N: p.N, f: fr(p.a, p.b) };
    if (p.kind === 'whole') return { M: p.M, f: fr(p.a, p.b) };
    if (p.kind === 'sum' || p.kind === 'diff') return { x: fr(p.x[0], p.x[1]), y: fr(p.y[0], p.y[1]) };
    return null;
  }
  // заполнить шаблон: числа — только из движка
  function fill(t, p) {
    const v = values(p); if (!v) return null;
    let bad = false;
    const put = str => str.replace(/\{(\w)(?:\|([^|}]+)\|([^|}]+)\|([^|}]+))?\}/g, (m, key, one, few, many) => {
      if (!(key in v)) { bad = true; return m; }
      return one ? pl(+v[key], one, few, many) : String(v[key]);
    });
    const s = put(t.s), q = put(t.q);
    return bad ? null : { story: s, question: q };
  }
  // примерно половина задач — про интересы ребёнка; ответ, проверка и подсказки по ошибкам не меняются
  function apply(task, interests, rnd = Math.random) {
    if (!task || !task.p || !Array.isArray(interests) || !interests.length || rnd() >= 0.5) return task;
    const id = interests[Math.floor(rnd() * interests.length)], p = task.p;
    // сумма больше целого: «какую часть пути» не годится — только сюжеты про количества (литры, часы)
    const over = p.kind === 'sum' && p.x[0] / p.x[1] + p.y[0] / p.y[1] > 1;
    const list = ((BANK[id] && BANK[id][p.kind]) || []).filter(t => !over || t.over);
    if (!list.length) return task;
    const out = fill(list[Math.floor(rnd() * list.length)], p);
    if (!out) return task;
    return { ...task, story: out.story, question: out.question, interest: id, figure: null, figureIsHint: false };
  }
  // автопроверка банка (тест и tools): все метки известны и подходят виду, нет своих цифр, длина до 200
  function check() {
    const errs = [], need = { left: ['n', 'k', 'r'], shaded: ['n', 'k', 'r'], part: ['N', 'f'], whole: ['M', 'f'], sum: ['x', 'y'], diff: ['x', 'y'] };
    for (const it of INTERESTS) for (const kind of Object.keys(need)) {
      const list = (BANK[it.id] || {})[kind];
      if (!list || !list.length) { errs.push(`${it.id}/${kind}: нет сюжетов`); continue; }
      list.forEach((t, i) => {
        const all = t.s + ' ' + t.q, keys = [...all.matchAll(/\{(\w)/g)].map(m => m[1]);
        if (/\d/.test(all)) errs.push(`${it.id}/${kind}/${i}: цифры в тексте`);
        if (keys.some(k => !KNOWN.includes(k) || !need[kind].includes(k))) errs.push(`${it.id}/${kind}/${i}: чужая метка`);
        if (!/\?$/.test(t.q)) errs.push(`${it.id}/${kind}/${i}: вопрос без «?»`);
        if (all.replace(/\{[^}]*\}/g, '00').length > 200) errs.push(`${it.id}/${kind}/${i}: длиннее 200`);
      });
    }
    return errs;
  }
  root.VEKTOR_STORIES = { INTERESTS, BANK, fill, apply, check, values };
